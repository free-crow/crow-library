// Import only the 43 reviewed editions pinned by the manifest. Other local TXT files are excluded.
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import opencc from "opencc-js";

const root = new URL("../", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("siku-batch-001.json", import.meta.url), "utf8"));
const simplify = opencc.Converter({ from: "tw", to: "cn" });
const books = [];
const ids = new Set();
const editions = new Set();
await mkdir(new URL("public/books/text/", root), { recursive: true });

for (const entry of manifest.books) {
  const raw = await readFile(new URL(entry.file, root));
  const normalizedText = raw.toString("utf8").replace(/\r\n?/g, "\n");
  if (createHash("sha256").update(normalizedText).digest("hex") !== entry.sha256) {
    throw new Error(`Source changed; review the volume boundaries before importing ${entry.file}`);
  }
  const lines = normalizedText.split("\n");
  const originalTitle = lines[0].trim();
  const author = lines[1].trim();
  if (ids.has(entry.id) || editions.has(originalTitle)) throw new Error("Duplicate Siku edition");
  ids.add(entry.id);
  editions.add(originalTitle);
  const header = lines.slice(0, entry.chapters[0].line - 1).filter(Boolean);
  const sourceUrl = header.find((line) => line.startsWith("來源："))?.slice(3);
  const revision = header.find((line) => line.startsWith("擷取時的全覽頁："))?.split("：").slice(1).join("：");
  const history = header.find((line) => line.startsWith("編輯歷史："))?.slice(5);
  if (!sourceUrl || !revision || !history || !header.some((line) => line.includes("CC BY-SA 4.0"))) {
    throw new Error(`Missing provenance for ${entry.id}`);
  }
  const chapters = entry.chapters.map((section, index) => {
    if (lines[section.line - 1] !== section.title) throw new Error(`Invalid boundary in ${entry.id}`);
    const nextSection = entry.chapters[index + 1];
    const end = nextSection ? nextSection.line - 1 : lines.length;
    const paras = lines.slice(section.line, end).join("\n").trim().split(/\n\s*\n/).filter(Boolean);
    if (!paras.length) throw new Error(`Empty volume in ${entry.id}`);
    return { title: section.title, paras };
  });
  // Preserve every non-whitespace character of the archived body, including old annotations.
  const originalBody = lines.slice(entry.chapters[0].line - 1).join("\n").replace(/\s/g, "");
  const parsedBody = chapters.map((chapter) => chapter.title + chapter.paras.join("")).join("").replace(/\s/g, "");
  if (originalBody !== parsedBody) throw new Error(`Text loss in ${entry.id}`);
  const notice = header.find((line) => line.startsWith("本 TXT")) || "";
  const attribution = `${originalTitle}，${author}。四庫全書本；中文維基文庫貢獻者轉錄。固定版本 ${revision}；貢獻者歷史 ${history}。${notice} 網站依原 TXT 分卷轉為章節 JSON，正文保留原字及古注。`;
  books.push({
    id: entry.id,
    title: simplify(originalTitle),
    author: simplify(author),
    categoryId: "phil-cn",
    tags: ["儒家", "四库全书", originalTitle],
    intro: `${originalTitle}，作者署名為「${author}」。收錄 ${chapters.length} 個分卷或書前、附錄單元。${notice}`,
    originalLanguage: "中文（文言文）",
    format: "TXT",
    copyright: {
      status: "approved",
      basis: "四庫舊本原作及古注已屬公有領域；數位轉錄中的開放授權部分依 CC BY-SA 4.0 使用",
      rightsHolder: "古籍原文為公有領域；適用開放授權的數位轉錄部分署名中文維基文庫貢獻者",
      licenseName: "古籍公版原文 / 數位轉錄 CC BY-SA 4.0",
      licenseUrl: "https://creativecommons.org/licenses/by-sa/4.0/",
      permissionScope: "在線閱讀 / 下載 / 格式轉換 / AI 輔助閱讀（摘要、解釋與短引）；轉錄的再分發與改編須署名、保留來源並依相同方式共享",
      attributionText: attribution,
      sourceUrl,
      sourceDate: "2026-11-26",
      reviewedBy: "版本與來源核對（原始 TXT 批次 3d29143）",
      reviewedAt: "2026-11-26",
    },
    aiAllowed: true,
    heat: 0,
    updatedAt: "2026-11-26",
    chapters: [],
    hasFullText: true,
  });
  const content = JSON.stringify({
    id: entry.id,
    source: sourceUrl,
    sourceFile: entry.file,
    sourceSha256: entry.sha256,
    revision,
    contributorHistory: history,
    license: "https://creativecommons.org/licenses/by-sa/4.0/",
    attribution,
    chapters,
  });
  const destination = new URL(`public/books/text/${entry.id}.json`, root);
  try {
    const existing = await readFile(destination, "utf8");
    if (existing !== content) throw new Error(`Refusing to replace existing book text: ${entry.id}`);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    await writeFile(destination, content);
  }
}
if (books.length !== 43) throw new Error("Expected exactly 43 reviewed Siku editions");
await writeFile(new URL("src/lib/books.siku.generated.ts", root),
  '// Generated by scripts/import-siku.mjs from the pinned, reviewed TXT batch.\nimport type { Book } from "./types";\n\nexport const SIKU_BOOKS: Book[] = ' +
  JSON.stringify(books, null, 2) + ";\n");
console.log(`Imported ${books.length} Siku editions with source credits and original text preserved.`);
